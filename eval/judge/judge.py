import os
import json
import glob
import re
import sys
import time
import argparse
from vllm import LLM, SamplingParams
from transformers import AutoTokenizer

os.environ['VLLM_WORKER_MULTIPROC_METHOD'] = 'spawn'

# ==============================================================================
#                               CONFIGURATION
# ==============================================================================

# 默认路径锚定到仓库根目录，与当前工作目录无关
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

FLAT_QA_JSONL  = os.path.join(REPO_ROOT, "anno_data", "SPACE.jsonl")
CAPTION_DIR    = os.path.join(REPO_ROOT, "caption_results")
OUTPUT_DIR     = os.path.join(REPO_ROOT, "eval_results")
CHECKPOINT_DIR = os.path.join(OUTPUT_DIR, "checkpoints")

MODEL_ID               = "Models/gemma-3-27b-it-text-only/"
GPUS_PER_NODE          = 8
TENSOR_PARALLEL_SIZE   = 8
GPU_MEMORY_UTILIZATION = 0.3
MAX_MODEL_LEN          = 4096
BATCH_SIZE             = 2048
# 截断异常超长的 caption（如 thinking 模型泄漏的推理链），
# 否则单条超过 max_model_len 的 prompt 会让 vLLM 拒绝整个 batch
MAX_CAPTION_CHARS      = 6000

VALID_CATEGORIES = ("Correct", "Incorrect", "Not Mentioned")

# ==============================================================================
#                               PROMPTS
# ==============================================================================

SYSTEM_PROMPT = """You are a strict and precise evaluator for image caption quality assessment.
Your task is to determine whether a generated caption contains the correct information to answer a given question about an image.
Always output valid JSON only, with no markdown, no extra text."""

USER_PROMPT_TEMPLATE = """You are given:
- [Generated Caption]: A caption describing an image, generated by a vision-language model.
- [Question]: A specific question about the image.
- [Ground Truth Answer]: The correct answer to the question, derived from a human-verified description.

Your task is to classify how well the [Generated Caption] covers the information needed to answer the [Question], compared to the [Ground Truth Answer].

## Classification Categories
Choose exactly ONE of the following:
- "Correct": The caption contains information that matches the ground truth answer to the question, even if some minor details are missing or phrased differently.
- "Incorrect": The caption mentions the relevant information but contradicts in a wrong direction or significantly differs from the ground truth answer.
- "Not Mentioned": The caption does not mention the subject of the question at all.

## Input
[Generated Caption]: {caption}

[Question]: {question}

[Ground Truth Answer]: {answer}

## Output Format
Output a JSON object with exactly two keys:
- "reasoning": A brief step-by-step analysis (2-3 sentences) comparing the caption against the question and ground truth.
- "category": One of exactly: "Correct", "Incorrect", "Not Mentioned"

Output the JSON object only. No markdown fences, no extra text."""

