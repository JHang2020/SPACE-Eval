#                               HELPERS
# ==============================================================================

def get_mpi_info():
    rank = int(os.environ.get('OMPI_COMM_WORLD_RANK',
               os.environ.get('PMI_RANK',
               os.environ.get('RANK', 0))))
    world_size = int(os.environ.get('OMPI_COMM_WORLD_SIZE',
                     os.environ.get('PMI_SIZE',
                     os.environ.get('WORLD_SIZE', 1))))
    return rank, world_size


def setup_gpu_visibility(rank, tp_size, total_gpus):
    if total_gpus % tp_size != 0:
        raise ValueError(f"Total GPUs {total_gpus} not divisible by TP={tp_size}.")
    num_workers = total_gpus // tp_size
    local_rank  = rank % num_workers
    start_gpu   = local_rank * tp_size
    visible     = ",".join(str(i) for i in range(start_gpu, start_gpu + tp_size))
    os.environ['CUDA_VISIBLE_DEVICES'] = visible
    return visible


def parse_llm_output(text: str) -> dict:
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()
    text = text.replace("```json", "").replace("```", "").strip()

    match = re.search(r"\{[\s\S]*\}", text)
    if match:
        try:
            parsed    = json.loads(match.group(0))
            reasoning = parsed.get("reasoning", "").strip()
            category  = parsed.get("category", "").strip()
            for valid in VALID_CATEGORIES:
                if valid.lower() == category.lower():
                    category = valid
                    break
            if category in VALID_CATEGORIES:
                return {"reasoning": reasoning, "category": category}
        except Exception:
            pass

    return {"reasoning": f"[PARSE_FAIL] {text[:150]}", "category": "Parse Error"}


def load_flat_qa(jsonl_path: str) -> dict:
    mapping = {}
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
                rid  = item["raw_id"]
                if rid not in mapping:
                    mapping[rid] = []
                mapping[rid].append(item)
            except (json.JSONDecodeError, KeyError):
                continue
    print(f"Loaded flat_qa: {sum(len(v) for v in mapping.values())} QA pairs "
          f"across {len(mapping)} images.")
    return mapping


def load_caption_file(caption_path: str) -> dict:
    mapping = {}
    with open(caption_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item    = json.loads(line)
                caption = item.get("caption", "").strip()
                if caption and not item.get("error"):
                    mapping[item["raw_id"]] = caption
            except (json.JSONDecodeError, KeyError):
                continue
    print(f"Loaded captions: {len(mapping)} images.")
    return mapping


def load_finished_qa_ids(ckpt_path: str) -> set:
    """只把拿到有效分类的条目算作已完成，Parse Error 条目下次运行自动重试。"""
    finished = set()
    if not os.path.exists(ckpt_path):
        return finished
    with open(ckpt_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
                if item.get("eval_category") in VALID_CATEGORIES:
                    finished.add(item["qa_id"])
            except (json.JSONDecodeError, KeyError):
                pass
    return finished


def build_prompt(tokenizer, caption: str, question: str, answer: str) -> str:
    if len(caption) > MAX_CAPTION_CHARS:
        caption = caption[:MAX_CAPTION_CHARS] + " ...[truncated]"
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user",   "content": USER_PROMPT_TEMPLATE.format(
            caption=caption, question=question, answer=answer
        )},
    ]
    return tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
        enable_thinking=False,
    )


def wait_for_all_ranks(ckpt_dir: str, model_name: str, rank: int, world_size: int):
    """
    用 done-flag 文件做跨进程同步：
    每个 rank 写完后创建自己的 flag 文件，rank 0 轮询等待所有 flag 出现。
    """
    flag_path = os.path.join(ckpt_dir, f"{model_name}_rank{rank}_DONE.flag")
    with open(flag_path, "w") as f:
        f.write(f"rank {rank} done")

    if rank != 0:
        return

    print(f"[Rank 0] Waiting for all {world_size} ranks to finish [{model_name}]...")
    pending_ranks = set(range(world_size))
    last_log = time.time()
    while pending_ranks:
        pending_ranks = {r for r in pending_ranks if not os.path.exists(
            os.path.join(ckpt_dir, f"{model_name}_rank{r}_DONE.flag"))}
        if not pending_ranks:
            break
        if time.time() - last_log > 60:
            print(f"[Rank 0] Still waiting for ranks {sorted(pending_ranks)} [{model_name}]")
            last_log = time.time()
        time.sleep(3)
    print(f"[Rank 0] All ranks done for [{model_name}], merging...")


def merge_and_save(ckpt_dir: str, model_name: str, output_dir: str, expected_total: int):
    """Rank 0 专用：合并所有 rank checkpoint，有效分类条目优先，并做完整性检查。"""
    output_path = os.path.join(output_dir, f"{model_name}.jsonl")
    best = {}

    # 用 glob 而不是 range(world_size)，兼容历史运行留下的不同 world_size 的 checkpoint
    for ckpt in sorted(glob.glob(os.path.join(ckpt_dir, f"{model_name}_rank*.jsonl"))):
        with open(ckpt, "r", encoding="utf-8") as fin:
            for line in fin:
                line = line.strip()
                if not line:
                    continue
                try:
                    item  = json.loads(line)
                    qa_id = item["qa_id"]
                except (json.JSONDecodeError, KeyError):
                    continue
                old = best.get(qa_id)
                if old is None or (item.get("eval_category") in VALID_CATEGORIES
                                   and old.get("eval_category") not in VALID_CATEGORIES):
                    best[qa_id] = item

    # 先写临时文件再原子替换，中途崩溃不会损坏已有结果
    tmp_path = output_path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as fout:
        for item in best.values():
            fout.write(json.dumps(item, ensure_ascii=False) + "\n")
    os.replace(tmp_path, output_path)

    n_invalid = sum(1 for v in best.values()
                    if v.get("eval_category") not in VALID_CATEGORIES)
    print(f"[Rank 0] [{model_name}] Merged {len(best)} entries -> {output_path}")
    if n_invalid:
        print(f"[WARN] [{model_name}] {n_invalid} entries have no valid category "
              f"(will be retried on next run).")
    if len(best) < expected_total:
        print(f"[WARN] [{model_name}] Incomplete: {len(best)}/{expected_total} QA evaluated; "
              f"rerun the same command to fill the gap.")
    return len(best)


# ==============================================================================
#                               CORE: evaluate one caption file
# ==============================================================================

def evaluate_one_caption_file(
    caption_path: str,
    flat_qa_map:  dict,
    model,
    tokenizer,
    sampling:     SamplingParams,
    rank:         int,
    world_size:   int,
):
    model_name = os.path.splitext(os.path.basename(caption_path))[0]
    ckpt_path  = os.path.join(CHECKPOINT_DIR, f"{model_name}_rank{rank}.jsonl")

    # 清掉上次中断运行残留的完成标记，避免 rank 0 提前合并
    stale_flag = os.path.join(CHECKPOINT_DIR, f"{model_name}_rank{rank}_DONE.flag")
    if os.path.exists(stale_flag):
        os.remove(stale_flag)

    caption_map = load_caption_file(caption_path)

    # 展开成 (qa_item + caption) 的完整列表
    all_tasks = []
    for raw_id, caption in caption_map.items():
        if raw_id not in flat_qa_map:
            continue
        for qa_item in flat_qa_map[raw_id]:
            all_tasks.append({
                "qa_id":        qa_item["qa_id"],
                "raw_id":       raw_id,
                "image_path":   qa_item["image_path"],
                "category_id":  qa_item["category_id"],
                "question":     qa_item["question"],
                "ground_truth": qa_item["ground_truth"],
                "caption":      caption,
                "model_name":   model_name,
            })

    # 按 rank 分片
    my_tasks = [t for i, t in enumerate(all_tasks) if i % world_size == rank]
    print(f"[Rank {rank}] [{model_name}] Total={len(all_tasks)}, Mine={len(my_tasks)}")

    # 断点续传
    finished_ids = load_finished_qa_ids(ckpt_path)
    pending      = [t for t in my_tasks if t["qa_id"] not in finished_ids]
    print(f"[Rank {rank}] [{model_name}] Pending={len(pending)} (skipped {len(finished_ids)})")

    # 批量推理，每 batch 立即写入 checkpoint
    n_failed = 0
    for i in range(0, len(pending), BATCH_SIZE):
        batch   = pending[i: i + BATCH_SIZE]
        prompts = [
            build_prompt(tokenizer, t["caption"], t["question"], t["ground_truth"])
            for t in batch
        ]

        try:
            outputs = model.generate(prompts, sampling_params=sampling)
            texts   = [out.outputs[0].text for out in outputs]
        except Exception as e:
            # 整批失败时降级为逐条推理，只跳过真正有问题的样本
            print(f"[Rank {rank}] [{model_name}] Batch failed ({e}); "
                  f"falling back to per-item inference.")
            texts = []
            for p in prompts:
                try:
                    out = model.generate([p], sampling_params=sampling, use_tqdm=False)
                    texts.append(out[0].outputs[0].text)
                except Exception:
                    texts.append(None)

        with open(ckpt_path, "a", encoding="utf-8") as f:
            for task, text in zip(batch, texts):
                if text is None:
                    n_failed += 1
                    continue  # 不写入，留给下次运行重试
                parsed = parse_llm_output(text)
                entry  = {
                    "qa_id":          task["qa_id"],
                    "raw_id":         task["raw_id"],
                    "image_path":     task["image_path"],
                    "category_id":    task["category_id"],
                    "model_name":     task["model_name"],
                    "question":       task["question"],
                    "ground_truth":   task["ground_truth"],
                    "caption":        task["caption"],
                    "eval_reasoning": parsed["reasoning"],
                    "eval_category":  parsed["category"],
                }
                f.write(json.dumps(entry, ensure_ascii=False) + "\n")

        print(f"[Rank {rank}] [{model_name}] {min(i + BATCH_SIZE, len(pending))}/{len(pending)}")

    if n_failed:
        print(f"[WARN] [Rank {rank}] [{model_name}] {n_failed} QA failed inference; "
              f"rerun the same command to retry them.")

    # ── 同步：等所有 rank 写完，再由 rank 0 合并 ──────────────────────────────
    wait_for_all_ranks(CHECKPOINT_DIR, model_name, rank, world_size)

    if rank == 0:
        total = merge_and_save(CHECKPOINT_DIR, model_name, OUTPUT_DIR,
                               expected_total=len(all_tasks))
        # 清理本模型的 flag 文件（不删 checkpoint，保留断点信息）
        for r in range(world_size):
            flag = os.path.join(CHECKPOINT_DIR, f"{model_name}_rank{r}_DONE.flag")
            if os.path.exists(flag):
                os.remove(flag)
        print(f"[Rank 0] [{model_name}] Done. Total QA evaluated: {total}")
    # 非 rank-0 进程直接进入下一个 caption 文件：
    # 各文件的 checkpoint 互不冲突，rank 0 合并当前文件时其他 rank 先跑后面的即可


# ==============================================================================
#                               MAIN
# ==============================================================================

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--caption_file", type=str, default=None)
    parser.add_argument("--caption_dir",  type=str, default=CAPTION_DIR)
    parser.add_argument("--flat_qa",      type=str, default=FLAT_QA_JSONL)
    parser.add_argument("--judge_model",  type=str, default=MODEL_ID)
    args = parser.parse_args()

    RANK, WORLD_SIZE = get_mpi_info()

    try:
        visible = setup_gpu_visibility(RANK, TENSOR_PARALLEL_SIZE, GPUS_PER_NODE)
        print(f"[Rank {RANK}] CUDA_VISIBLE_DEVICES={visible}")
    except Exception as e:
        print(e); sys.exit(1)

    os.makedirs(OUTPUT_DIR,     exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)

    if args.caption_file:
        caption_files = [args.caption_file]
    else:
        caption_files = sorted(glob.glob(os.path.join(args.caption_dir, "*.jsonl")))

    if not caption_files:
        print("No caption files found."); sys.exit(0)

    if RANK == 0:
        print(f"Caption files to evaluate: {[os.path.basename(p) for p in caption_files]}")

    flat_qa_map = load_flat_qa(args.flat_qa)

    print(f"[Rank {RANK}] Loading judge model...")
    tokenizer = AutoTokenizer.from_pretrained(args.judge_model, trust_remote_code=True)
    model = LLM(
        model=args.judge_model,
        tensor_parallel_size=TENSOR_PARALLEL_SIZE,
        trust_remote_code=True,
        dtype="bfloat16",
        max_model_len=MAX_MODEL_LEN,
        gpu_memory_utilization=GPU_MEMORY_UTILIZATION,
        enforce_eager=True,
        limit_mm_per_prompt={"video": 0, "image": 0},
        mm_encoder_tp_mode="data",
        enable_expert_parallel=False,
    )
    sampling = SamplingParams(temperature=0.0, top_p=0.9, max_tokens=512)

    # 逐文件评估
    for caption_path in caption_files:
        if RANK == 0:
            print(f"\n{'='*60}")
            print(f"Evaluating: {os.path.basename(caption_path)}")
            print(f"{'='*60}")
        evaluate_one_caption_file(
            caption_path, flat_qa_map, model, tokenizer, sampling, RANK, WORLD_SIZE
        )

    if RANK == 0:
        print("\nAll caption files evaluated.")


if __name__ == "__main__":
    main()
